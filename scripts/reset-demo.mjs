// Resets the two synthetic demo teams (Platform, Backend) to their seeded
// state so every tester starts from the same village: team name and cohort
// tags, capabilities, starter buildings, and the fully consented fictional
// roster. It never touches the live Solstice team, ingested signals, roles,
// rate limits or feedback.
//
// The SQL is built from the repo's own seed migrations (0002 teams and
// buildings, 0005 rosters), so it cannot drift from a fresh install.
//
// Usage:
//   node scripts/reset-demo.mjs              # print the SQL only (dry run)
//   node scripts/reset-demo.mjs --local      # apply to the local D1 (wrangler dev)
//   node scripts/reset-demo.mjs --remote     # apply to the production D1 (asks wrangler)

import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('../', import.meta.url))
const DEMO = ['platform', 'backend']
const mode = process.argv.includes('--remote') ? 'remote' : process.argv.includes('--local') ? 'local' : 'dry-run'

const seedLines = (file, table) =>
  fs.readFileSync(path.join(ROOT, 'migrations', file), 'utf8')
    .split('\n')
    .filter((l) => l.startsWith(`INSERT INTO ${table} `) && DEMO.some((id) => l.includes(`'${id}'`)))

// 0005 seeds rosters as one multi-row INSERT; keep only the demo-team rows.
function rosterInsert() {
  const sql = fs.readFileSync(path.join(ROOT, 'migrations', '0005_roster_consent.sql'), 'utf8')
  const rows = sql.split('\n').filter((l) => DEMO.some((id) => l.trim().startsWith(`('${id}'`)))
  const values = rows.map((r) => r.trim().replace(/[,;]$/, '')).join(',\n  ')
  return `INSERT INTO roster_members (team_id, name, role, consented, consent_updated_at, updated_at) VALUES\n  ${values};`
}

const ids = DEMO.map((id) => `'${id}'`).join(', ')
const teams = seedLines('0002_seed.sql', 'teams').map((l) => l.replace('INSERT INTO teams', 'INSERT OR REPLACE INTO teams'))
const sql = [
  '-- Growth demo reset (generated by scripts/reset-demo.mjs)',
  `DELETE FROM buildings WHERE team_id IN (${ids});`,
  `DELETE FROM roster_members WHERE team_id IN (${ids});`,
  ...teams,
  ...seedLines('0002_seed.sql', 'buildings'),
  rosterInsert(),
].join('\n')

if (mode === 'dry-run') {
  console.log(sql)
  console.log('\n-- dry run: nothing applied. Use --local or --remote to apply.')
  process.exit(0)
}

const file = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'growth-reset-')), 'reset.sql')
fs.writeFileSync(file, sql)
const r = spawnSync('npx', ['wrangler', 'd1', 'execute', 'growth-db', `--${mode}`, '--file', file], { cwd: ROOT, stdio: 'inherit' })
process.exit(r.status ?? 1)
